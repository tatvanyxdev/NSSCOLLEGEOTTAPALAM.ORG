const UUID_REGEX = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

/**
 * Validates if an input string is a valid UUID format.
 */
export function isValidUuid(val: any): boolean {
  return typeof val === 'string' && UUID_REGEX.test(val);
}

/**
 * Resolves any mock or legacy identifier (e.g. 'dept-com', 'fac-1', 'ay-2026-27')
 * to a standardized RFC 4122 UUID. If input is already a valid UUID, returns it.
 * If input cannot be found, generates a deterministic valid UUID from the input string.
 */
export function toValidUuid(val: any): string | null {
  if (!val || typeof val !== 'string') return null;
  const trimmed = val.trim();
  if (!trimmed) return null;
  if (UUID_REGEX.test(trimmed)) return trimmed;

  // Check lookup map
  if (UUID_MAP[trimmed]) return UUID_MAP[trimmed];

  // Try lowercase lookup
  const lower = trimmed.toLowerCase();
  if (UUID_MAP[lower]) return UUID_MAP[lower];

  // Deterministic fallback ensures PostgreSQL never throws 22P02 invalid input syntax
  return deterministicUuidFromString(trimmed);
}

/**
 * Generates a pseudo-UUID deterministically from a string seed if needed.
 */
export function deterministicUuidFromString(seed: string): string {
  let hash = 0;
  for (let i = 0; i < seed.length; i++) {
    hash = ((hash << 5) - hash) + seed.charCodeAt(i);
    hash |= 0;
  }
  const hex = Math.abs(hash).toString(16).padStart(8, '0');
  return `ffffffff-ffff-4fff-8fff-${hex.padEnd(12, '0')}`;
}
